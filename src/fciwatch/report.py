"""Make one self-contained HTML report from a drift table.

The report has:
  * a summary table (one line per channel pair, with OK / CHECK),
  * a chart of daily drift in kelvin, with the alert level drawn as dashed lines,
  * a chart of the scene-temperature slope (a sanity check of the method).

Charts use Apache ECharts. By default the page loads it from a CDN, so the report
needs internet when you open it. If you want a fully offline file, pass
`echarts_path` with a local copy of echarts.min.js and it will be inlined.
"""

from __future__ import annotations

import html
import json
from pathlib import Path

import pandas as pd

from .channels import PAIRS

ECHARTS_CDN = "https://cdn.jsdelivr.net/npm/echarts@5.5.1/dist/echarts.min.js"

_TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>__TITLE__</title>
__ECHARTS_TAG__
<style>
  body { font-family: system-ui, sans-serif; margin: 2rem auto; max-width: 62rem; padding: 0 1rem;
         color: #1b1f24; background: #fff; }
  h1 { margin-bottom: .2rem; }
  .sub { color: #57606a; margin-top: 0; }
  .warn { background: #fff4e5; border-left: 4px solid #d97706; padding: .6rem .9rem; margin: 1rem 0; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0 2rem; font-size: .92rem; }
  th, td { border-bottom: 1px solid #d0d7de; padding: .4rem .6rem; text-align: right; }
  th:first-child, td:first-child { text-align: left; }
  .OK { color: #1a7f37; font-weight: 600; }
  .CHECK { color: #cf222e; font-weight: 600; }
  .NODATA { color: #57606a; font-weight: 600; }
  .chart { width: 100%; height: 22rem; margin-bottom: 2rem; }
  .note { color: #57606a; font-size: .85rem; }
  @media (prefers-color-scheme: dark) {
    body { background: #0d1117; color: #e6edf3; }
    th, td { border-bottom-color: #30363d; }
    .sub, .note { color: #9da7b3; }
    .warn { background: #2b1d0a; }
  }
</style>
</head>
<body>
<h1>__TITLE__</h1>
<p class="sub">FCI minus SEVIRI brightness temperature, relative to a baseline period.</p>
__BANNER__
<h2>Summary</h2>
__TABLE__
<h2>Daily drift (K)</h2>
<div id="drift" class="chart"></div>
<h2>Scene-temperature slope (K per K)</h2>
<div id="slope" class="chart"></div>
<p class="note">Drift is a relative number: zero means "same as the baseline period", not
"perfectly calibrated". Alert level: &plusmn;__THRESHOLD__ K (chosen by the user, not an official
requirement). Generated by fciwatch __VERSION__.</p>
<script>
const DATA = __DATA__;
const dark = window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
const textColor = dark ? "#e6edf3" : "#1b1f24";

function lineChart(elId, key, yName, withThreshold) {
  const series = DATA.pairs.map((p, i) => {
    const s = { name: p.label, type: "line", showSymbol: false, data: p[key] };
    if (withThreshold && i === 0) {
      s.markLine = { symbol: "none", silent: true, lineStyle: { type: "dashed", color: "#cf222e" },
        data: [{ yAxis: DATA.threshold }, { yAxis: -DATA.threshold }], label: { show: false } };
    }
    return s;
  });
  const chart = echarts.init(document.getElementById(elId));
  chart.setOption({
    textStyle: { color: textColor },
    tooltip: { trigger: "axis" },
    legend: { top: 0, textStyle: { color: textColor } },
    grid: { left: 55, right: 20, top: 40, bottom: 60 },
    xAxis: { type: "time" },
    yAxis: { type: "value", name: yName, scale: true },
    dataZoom: [{ type: "inside" }, { type: "slider" }],
    series: series,
  });
  window.addEventListener("resize", () => chart.resize());
}
lineChart("drift", "drift", "drift [K]", true);
lineChart("slope", "slope", "slope [K/K]", false);
</script>
</body>
</html>
"""


def _safe_json(obj) -> str:
    """JSON that is safe to put inside a <script> tag."""
    return json.dumps(obj).replace("</", "<\\/")


def _fmt(x, digits: int = 2) -> str:
    return "n/a" if pd.isna(x) else f"{x:+.{digits}f}"


def _table(summary: pd.DataFrame) -> str:
    head = (
        "<tr><th>Channel pair</th><th>Spectral shift (um)</th><th>First day</th><th>Last day</th>"
        "<th>Days</th><th>Baseline (K)</th><th>Recent drift (K)</th><th>Max |drift| (K)</th>"
        "<th>Alert days</th><th>Status</th></tr>"
    )
    rows = []
    for _, r in summary.iterrows():
        pair = PAIRS.get(r["pair"])
        shift = f"{pair.centre_shift_um:+.2f}" if pair else "n/a"
        cls = r["status"].replace(" ", "")
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(r['pair']))}</td><td>{shift}</td>"
            f"<td>{html.escape(r['first_day'])}</td><td>{html.escape(r['last_day'])}</td>"
            f"<td>{r['n_days']}</td><td>{_fmt(r['baseline_k'])}</td>"
            f"<td>{_fmt(r['recent_drift_k'])}</td>"
            f"<td>{'n/a' if pd.isna(r['max_abs_drift_k']) else format(r['max_abs_drift_k'], '.2f')}</td>"
            f"<td>{r['n_alert_days']}</td>"
            f'<td class="{cls}">{html.escape(r["status"])}</td>'
            "</tr>"
        )
    return f"<table>{head}{''.join(rows)}</table>"


def build_report(
    daily: pd.DataFrame,
    slope_daily: pd.DataFrame,
    summary: pd.DataFrame,
    threshold_k: float,
    title: str = "FCI calibration watch",
    banner: str | None = None,
    echarts_path: str | Path | None = None,
) -> str:
    """Return the HTML text of the report."""
    from . import __version__

    pairs = []
    for pair, g in daily.groupby("pair"):
        g = g.sort_values("day")
        s = slope_daily[slope_daily["pair"] == pair].sort_values("day")
        pairs.append(
            {
                "label": str(pair),
                "drift": [
                    [d.strftime("%Y-%m-%d"), None if pd.isna(v) else round(float(v), 4)]
                    for d, v in zip(g["day"], g["drift"])
                ],
                "slope": [
                    [d.strftime("%Y-%m-%d"), None if pd.isna(v) else round(float(v), 4)]
                    for d, v in zip(s["day"], s["value"])
                ],
            }
        )

    if echarts_path:
        tag = "<script>" + Path(echarts_path).read_text(encoding="utf-8") + "</script>"
    else:
        tag = f'<script src="{ECHARTS_CDN}"></script>'

    banner_html = f'<div class="warn">{html.escape(banner)}</div>' if banner else ""

    out = _TEMPLATE
    for key, val in {
        "__TITLE__": html.escape(title),
        "__ECHARTS_TAG__": tag,
        "__BANNER__": banner_html,
        "__TABLE__": _table(summary),
        "__THRESHOLD__": f"{threshold_k:g}",
        "__VERSION__": __version__,
        "__DATA__": _safe_json({"pairs": pairs, "threshold": threshold_k}),
    }.items():
        out = out.replace(key, val)
    return out
